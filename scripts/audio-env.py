"""Extract normalized frame RMS for talkAt: audio-env.py input.mp3 output.ts frames [fps]."""
import array
import math
import subprocess
import sys
from pathlib import Path

src, out, frames = sys.argv[1], sys.argv[2], int(sys.argv[3])
fps = int(sys.argv[4]) if len(sys.argv) > 4 else 30
sr = 24000
decoded = subprocess.run(
    ["ffmpeg", "-v", "error", "-i", src, "-f", "s16le", "-ac", "1", "-ar", str(sr), "pipe:1"],
    check=True, capture_output=True,
).stdout
samples = array.array("h", decoded)
if sys.byteorder != "little":
    samples.byteswap()
raw = []
for f in range(frames):
    chunk = samples[int(f * sr / fps):int((f + 1) * sr / fps)]
    raw.append(math.sqrt(sum(v * v for v in chunk) / max(1, len(chunk))))
peak = sorted(raw)[int(len(raw) * 0.97)] or 1
values = [min(1, (v / peak) ** 0.7) for v in raw]
values = [round(v, 2) if v >= 0.06 else 0 for v in values]
lines = ["// Real mono voiceover RMS, one normalized sample per frame; generated by scripts/audio-env.py.",
         f"export const AUDIO_ENV_FPS = {fps};", "export const AUDIO_ENV: number[] = ["]
lines += ["  " + ",".join(f"{v:.2f}" for v in values[i:i+30]) + "," for i in range(0, frames, 30)]
Path(out).write_text("\n".join(lines) + "\n];\n", encoding="utf-8")
print(f"Envelope: {frames} samples at {fps} fps, {len(samples)/sr:.2f}s audio; {sum(v>0 for v in values)} active frames")
